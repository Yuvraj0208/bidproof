"""Shared vocabulary for evaluation.

The whole point of this subsystem is that a number on the Evaluation screen can
be trusted. Two rules follow from that, and they are enforced by the types rather
than by discipline:

1. **Every metric carries its sample size and where its ground truth came from.**
   A precision of 1.00 measured against PDFs generated to match the extractor's
   own patterns is not the same claim as 1.00 against hand-labelled tenders, and
   the screen must never let them look alike.

2. **"Not measured" is a first-class result.** A component with no ground truth
   reports `NO_GROUND_TRUTH` and shows what would be needed. It never reports a
   default, an estimate, or a zero that reads like a score.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum


class Status(str, Enum):
    MEASURED = "measured"
    # The evaluator exists but the data it needs does not.
    NO_GROUND_TRUTH = "no_ground_truth"
    # The thing being evaluated is not built yet.
    NOT_IMPLEMENTED = "not_implemented"
    # A dependency was missing or the run failed. Never silently a zero.
    ERROR = "error"


class GroundTruth(str, Enum):
    # Hand-labelled by a person against a real document.
    HUMAN_LABELLED = "human_labelled"
    # Generated by us, so the answer is known exactly (e.g. text rendered to an
    # image and then read back). Honest, but only tests what we generated.
    SYNTHETIC = "synthetic"
    # No labels: two implementations compared against each other, or a property
    # checked that must hold regardless of the answer.
    DERIVED = "derived"
    # Real production output scored by a checker that is itself part of the
    # product (e.g. the FactChecker). Real data, but not an independent oracle.
    SELF_REPORTED = "self_reported"
    NONE = "none"


@dataclass(frozen=True)
class Metric:
    """One measured number.

    `higher_is_better` is required because the UI colours by direction, and a
    character error rate coloured like an accuracy is a lie told in green.
    """

    key: str
    label: str
    value: float | None
    unit: str = ""
    higher_is_better: bool = True
    sample_size: int | None = None
    detail: str = ""

    def to_dict(self) -> dict:
        return {
            "key": self.key,
            "label": self.label,
            "value": self.value,
            "unit": self.unit,
            "higher_is_better": self.higher_is_better,
            "sample_size": self.sample_size,
            "detail": self.detail,
        }


@dataclass
class Evaluation:
    """The result of evaluating one component."""

    component: str
    label: str
    what_it_measures: str
    status: Status
    ground_truth: GroundTruth = GroundTruth.NONE
    metrics: list[Metric] = field(default_factory=list)
    # Shown verbatim when status is not MEASURED: what a person must do to turn
    # this into a real number.
    blocked_reason: str = ""
    how_to_fix: str = ""
    duration_s: float | None = None
    measured_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    def to_dict(self) -> dict:
        return {
            "component": self.component,
            "label": self.label,
            "what_it_measures": self.what_it_measures,
            "status": self.status.value,
            "ground_truth": self.ground_truth.value,
            "metrics": [m.to_dict() for m in self.metrics],
            "blocked_reason": self.blocked_reason,
            "how_to_fix": self.how_to_fix,
            "duration_s": self.duration_s,
            "measured_at": self.measured_at.isoformat(),
        }
